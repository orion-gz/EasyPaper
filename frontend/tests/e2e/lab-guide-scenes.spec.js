import { test, expect } from '@playwright/test'
import { mockBaseRoutes, gotoApp, reloadToLibrary } from './helpers.js'

async function openGuide(page, clock = true, scheme = 'dark') {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await mockBaseRoutes(page)
  await page.route('**/api/auth/me', route => route.fulfill({ json: { username: 'admin', role: 'master', lab_mode: true } }))
  for (const path of ['lab/inference', 'me/model-settings', 'lab/users']) await page.route(`**/api/${path}`, route => route.fulfill({ json: path === 'lab/users' ? [] : {} }))
  await gotoApp(page)
  if (scheme === 'light') {
    await page.locator('#sidebar-theme-toggle-btn').click()
    await expect(page.locator('body')).toHaveClass(/light-theme/)
  }
  if (!clock) {
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.emulateMedia({ reducedMotion: 'reduce' })
  }
  if (clock) {
    const now = new Date('2026-11-04T12:00:00Z')
    await page.clock.install({ time: now })
    await page.clock.pauseAt(now)
  }
  await page.evaluate(() => document.dispatchEvent(new CustomEvent('easypaper:open-settings', { detail: { category: 'tab-general' } })))
  await page.locator('#settings-nav-lab').click()
  await page.locator('#tab-lab .lab-introduction > button').first().click()
  const guide = page.locator('.lab-guide-dialog')
  return { errors, guide, canvas: guide.locator('.lab-scene-canvas'), pause: guide.locator('.lab-guide-controls button').nth(1), replay: guide.locator('.lab-guide-controls button').nth(2), scene: guide.locator('.lab-guide-controls button').nth(3), step: guide.locator('.lab-guide-footer button').last() }
}

async function finishScenes(scene) {
  while (await scene.isEnabled()) await scene.click()
}

test('commands animate individually and never advance automatically', async ({ page }) => {
  const { canvas, guide, pause, replay, scene } = await openGuide(page)
  for (const control of await guide.locator('.lab-guide-controls button').all()) {
    await expect(control).toHaveText('')
    await expect(control).toHaveAttribute('aria-label', /.+/)
    await expect(control).toHaveAttribute('title', await control.getAttribute('aria-label'))
    await expect(control.locator('svg[aria-hidden="true"]')).toHaveCount(1)
  }
  const pauseIcon = await pause.innerHTML()
  const command = canvas.locator('.lab-demo-command')
  await expect(command).toHaveCount(1)
  await page.clock.runFor(800)
  await expect(command).toHaveAttribute('data-phase', 'typing')
  await pause.click()
  expect(await pause.innerHTML()).not.toBe(pauseIcon)
  const frozen = await canvas.innerHTML()
  await page.clock.runFor(2000)
  expect(await canvas.innerHTML()).toBe(frozen)
  await pause.click()
  expect(await pause.innerHTML()).toBe(pauseIcon)
  await page.clock.runFor(1600)
  await expect(command).toHaveAttribute('data-phase', 'running')
  await page.clock.runFor(60000)
  await expect(command).toHaveAttribute('data-phase', 'complete')
  await expect(command).toContainText('sudo bash deploy/lab/install-docker.sh')
  await replay.click()
  await expect(canvas).toHaveAttribute('data-elapsed', '0')
  await scene.click()
  await page.clock.runFor(60000)
  await expect(command).toContainText('install-inference.sh')
  await page.keyboard.press('Escape')
  const closed = await canvas.innerHTML()
  await page.clock.runFor(20000)
  expect(await canvas.innerHTML()).toBe(closed)
})

