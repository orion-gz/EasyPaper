test('SSH launchers download current validated parameters without credentials', async ({ page }) => {
  const { guide, scene, step } = await openGuide(page, false)
  await finishScenes(scene)
  await step.click(); await step.click()
  await guide.locator('#lab-guide-param-host').fill('alice@gpu.example.edu')
  await expect(guide.locator('#lab-guide-param-user')).toHaveCount(0)
  await expect(guide.locator('#lab-guide-param-port')).toBeHidden()
  await guide.locator('.lab-guide-advanced summary').click()
  await guide.locator('#lab-guide-param-localPort').fill('19002')
  for (const [label, filename] of [['Linux/macOS', 'easypaper-connect.sh'], ['Windows', 'easypaper-connect.cmd']]) {
    const downloaded = page.waitForEvent('download')
    await guide.getByRole('button', { name: `SSH 실행 파일 · ${label}`, exact: true }).click()
    const file = await downloaded
    expect(file.suggestedFilename()).toBe(filename)
    const stream = await file.createReadStream()
    const chunks = []
    for await (const chunk of stream) chunks.push(chunk)
    const content = Buffer.concat(chunks).toString('utf8')
    expect(content).toContain('-L 127.0.0.1:19002:127.0.0.1:8000')
    expect(content).toContain('alice@gpu.example.edu')
    expect(content).not.toContain('StrictHostKeyChecking=no')
  }
  await guide.locator('#lab-guide-param-host').fill('bad;id')
  await expect(guide.getByRole('button', { name: 'SSH 실행 파일 · Windows', exact: true })).toBeDisabled()
  await guide.locator('#lab-guide-param-host').fill('alice@gpu.example.edu')
  await scene.click()
  await expect(guide.getByRole('button', { name: 'SSH 실행 파일 · Windows', exact: true })).toBeHidden()
})


