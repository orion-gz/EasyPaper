import { test, expect } from '@playwright/test'
import { mockBaseRoutes, gotoApp, reloadToLibrary } from './helpers.js'

async function openGuide(page, clock = true) {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await mockBaseRoutes(page)
  await page.route('**/api/auth/me', route => route.fulfill({ json: { username: 'admin', role: 'master', lab_mode: true } }))
  for (const path of ['lab/inference', 'me/model-settings', 'lab/users']) await page.route(`**/api/${path}`, route => route.fulfill({ json: path === 'lab/users' ? [] : {} }))
  await gotoApp(page)
  if (!clock) {
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.emulateMedia({ reducedMotion: 'reduce' })
  }
  if (clock) {
    const now = new Date('2026-11-04T12:00:00Z')
    await page.clock.install({ time: now })
    await page.clock.pauseAt(now)
  }
  await page.evaluate(() => document.dispatchEvent(new CustomEvent('easypaper:open-settings', { detail: { category: 'tab-general' } })))
  await page.locator('#settings-nav-lab').click()
  await page.locator('#tab-lab .lab-introduction > button').first().click()
  const guide = page.locator('.lab-guide-dialog')
  return { errors, guide, canvas: guide.locator('.lab-scene-canvas'), pause: guide.locator('.lab-guide-controls button').nth(1), replay: guide.locator('.lab-guide-controls button').nth(2), scene: guide.locator('.lab-guide-controls button').nth(3), step: guide.locator('.lab-guide-footer button').last() }
}

async function finishScenes(scene) {
  while (await scene.isEnabled()) await scene.click()
}

test('commands animate individually and never advance automatically', async ({ page }) => {
  const { canvas, pause, replay, scene } = await openGuide(page)
  const command = canvas.locator('.lab-demo-command')
  await expect(command).toHaveCount(1)
  await page.clock.runFor(800)
  await expect(command).toHaveAttribute('data-phase', 'typing')
  await pause.click()
  const frozen = await canvas.innerHTML()
  await page.clock.runFor(2000)
  expect(await canvas.innerHTML()).toBe(frozen)
  await pause.click()
  await page.clock.runFor(1600)
  await expect(command).toHaveAttribute('data-phase', 'running')
  await page.clock.runFor(60000)
  await expect(command).toHaveAttribute('data-phase', 'complete')
  await expect(command).toContainText('apt-get')
  await replay.click()
  await expect(canvas).toHaveAttribute('data-elapsed', '0')
  await scene.click()
  await page.clock.runFor(60000)
  await expect(command).toContainText('git clone')
  await page.keyboard.press('Escape')
  const closed = await canvas.innerHTML()
  await page.clock.runFor(20000)
  expect(await canvas.innerHTML()).toBe(closed)
})

test('installation gates connection, keeps SSH parameters and persists completion', async ({ page }) => {
  const { guide, scene, step, errors } = await openGuide(page)
  const connect = page.locator('#tab-lab .lab-introduction > button').nth(1)
  await expect(connect).toBeDisabled()
  await expect(step).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(connect).toBeDisabled()
  await page.locator('#tab-lab .lab-introduction > button').first().click()
  await finishScenes(scene)
  await step.click()
  await expect(guide.locator('.lab-guide-choices button').first()).toHaveAttribute('aria-pressed', 'true')
  await step.click()
  await guide.locator('#lab-guide-param-host').fill('gpu.example.edu')
  await guide.locator('#lab-guide-param-user').fill('alice')
  await guide.locator('#lab-guide-param-port').fill('2222')
  await guide.locator('#lab-guide-param-localPort').fill('19000')
  await expect(guide.locator('.lab-guide-snippet code')).toContainText('-L 19000:127.0.0.1:8000 -p 2222 alice@gpu.example.edu')
  await page.evaluate(() => { window.copied = ''; Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => { window.copied = value } } }) })
  await guide.locator('.lab-guide-snippet button').click()
  expect(await page.evaluate(() => window.copied)).toContain('alice@gpu.example.edu')
  await guide.locator('#lab-guide-param-host').fill('bad;touch /tmp/injected')
  await expect(guide.locator('.lab-guide-snippet button')).toBeDisabled()
  await expect(scene).toBeDisabled()
  await guide.locator('#lab-guide-param-host').fill('gpu.example.edu')
  await finishScenes(scene)
  await step.click()
  await expect(connect).toBeEnabled()
  await connect.click()
  await expect(guide.locator('.lab-guide-snippet code')).toContainText('alice@gpu.example.edu')
  await scene.click()
  await expect(guide.locator('.lab-guide-snippet code')).toHaveText('http://localhost:19000')
  await page.clock.runFor(5000)
  await expect(guide.locator('.lab-demo-input')).toHaveText(['http://localhost:19000', 'alice', '••••••••'])
  await step.click()
  await page.clock.resume()
  await reloadToLibrary(page)
  await page.evaluate(() => document.dispatchEvent(new CustomEvent('easypaper:open-settings', { detail: { category: 'tab-general' } })))
  await page.locator('#settings-nav-lab').click()
  await expect(connect).toBeEnabled()
  expect(errors).toEqual([])
})

test('systemd and HTTPS have separate install and connection instructions', async ({ page }) => {
  const { guide, scene, step, canvas } = await openGuide(page)
  await guide.locator('.lab-guide-choices button').nth(1).click()
  await finishScenes(scene)
  await expect(guide.locator('.lab-guide-snippet code')).toHaveText('sudo bash deploy/lab/install-systemd.sh')
  await step.click()
  await guide.locator('.lab-guide-choices button').nth(1).click()
  await step.click()
  // Initialize the administrator privately before publishing HTTPS.
  await expect(guide.locator('.lab-guide-snippet code')).toContainText('ssh ')
  await scene.click()
  await expect(guide.locator('.lab-guide-snippet code')).toHaveText('http://localhost:18000')
  await scene.click()
  await expect(canvas).toHaveAttribute('data-scene', 'network')
  await guide.locator('#lab-guide-param-domain').fill('papers.example.edu')
  await scene.click()
  await expect(guide.locator('.lab-guide-snippet code')).toContainText('install -y caddy')
  await scene.click()
  await expect(guide.locator('.lab-guide-snippet code')).toContainText("'papers.example.edu {'")
  await expect(guide.locator('.lab-guide-snippet code')).toContainText('reverse_proxy 127.0.0.1:8000')
  await finishScenes(scene)
  await step.click()
  await page.locator('#tab-lab .lab-introduction > button').nth(1).click()
  await expect(guide.locator('.lab-guide-snippet code')).toHaveText('https://papers.example.edu')
  await expect(guide.locator('#lab-guide-param-host')).toHaveCount(0)
  await guide.locator('#lab-guide-param-domain').fill('new.example.edu')
  await expect(guide.locator('.lab-demo-input').first()).toHaveText('https://new.example.edu')
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('denied') } } }))
  await guide.locator('.lab-guide-snippet button').click()
  await expect(guide.locator('.lab-guide-commands [role=status]')).not.toBeEmpty()
})

test('reduced motion, mobile and changing methods retain usable controls', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const { errors, guide, canvas, pause, scene, step } = await openGuide(page, false)
  await expect(pause).toBeHidden()
  await expect(canvas).toHaveAttribute('data-complete', 'true')
  await finishScenes(scene)
  await step.click()
  await step.click()
  await expect(guide.locator('#lab-guide-param-host')).toBeVisible()
  const controls = await guide.locator('.lab-guide-controls').boundingBox()
  expect(controls.y).toBeGreaterThanOrEqual(0)
  expect(controls.y + controls.height).toBeLessThanOrEqual(844)
  expect(controls.x + controls.width).toBeLessThanOrEqual(390)
  await page.screenshot({ animations: 'disabled', path: '/tmp/lab-guides-mobile.png' })
  await finishScenes(scene)
  await step.click()
  const connect = page.locator('#tab-lab .lab-introduction > button').nth(1)
  await expect(connect).toBeEnabled()
  await page.locator('#tab-lab .lab-introduction > button').first().click()
  await guide.locator('.lab-guide-choices button').nth(1).click()
  await page.keyboard.press('Escape')
  await expect(connect).toBeDisabled()
  expect(errors).toEqual([])
})
